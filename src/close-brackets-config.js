// ============================================================
// CodeMirror closeBrackets brackets 配置（单一事实源，便于测试）
// ------------------------------------------------------------
// 【关键约束】CodeMirror 6 的 closeBrackets 把 `brackets` 视为「连续成对」字符串：
//   索引 0&1 为一对、2&3 为一对……；自配对符号（ASCII ' " `）需将同一字符连续写两次。
//   若给成数组且长度非偶数对，或把开/闭符号混排，CM6 会按相邻两位强行配对，
//   导致 `(` 闭合到 `[`、`“` 闭合到 `` ` `` 等完全错乱的组合（参见原 BUG-4）。
//
// 本模块导出唯一权威的 BRACKET_PAIRS 数组与由其派生的 BRACKETS_STR 字符串。
// editor.js 仅 import BRACKETS_STR；tests/close-brackets-config.test.js 验证字符串正确性。
// ============================================================

export const BRACKET_PAIRS = [
  ['(', ')'], ['[', ']'], ['{', '}'], ['<', '>'],
  ["'", "'"], ['"', '"'], ['`', '`'],
  // 中英标点（开/闭为不同字符）：
  ['\u201c', '\u201d'], // " " 中文双引号（左/右）
  ['\u2018', '\u2019'], // ' ' 中文单引号（左/右）
  ['\uff08', '\uff09'], // （ ） 全角括号（左/右）
];

// 由 BRACKET_PAIRS 派生：相邻成对字符串，与 CM6 closeBrackets 解析规则一致。
export const BRACKETS_STR = BRACKET_PAIRS.map(p => p[0] + p[1]).join('');